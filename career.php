        document.addEventListener('DOMContentLoaded', function() {
            // Animate section titles on scroll
            const animateOnScroll = function() {
                const elements = document.querySelectorAll('.job-card');
                elements.forEach(element => {
                    const position = element.getBoundingClientRect();
                    // If the element is in the viewport
                    if(position.top < window.innerHeight && position.bottom >= 0) {
                        element.style.opacity = "1";
                    }
                });
            };
            
            // Run on load
            animateOnScroll();
            // Run on scroll
            window.addEventListener('scroll', animateOnScroll);
            
            // Job filtering
            const filterButtons = document.querySelectorAll('.filter-btn');
            const jobItems = document.querySelectorAll('.jon-item1');
            const noResults = document.getElementById('no-results');
            
            filterButtons.forEach(button => {
                button.addEventListener('click', function() {
                    // Update active button
                    filterButtons.forEach(btn => btn.classList.remove('active'));
                    this.classList.add('active');
                    
                    const filter = this.getAttribute('data-filter');
                    let itemsVisible = 0;
                    
                    // Filter jobs
                    jobItems.forEach(item => {
                        if (filter === 'all' || item.getAttribute('data-category').includes(filter)) {
                            item.style.display = 'block';
                            itemsVisible++;
                        } else {
                            item.style.display = 'none';
                        }
                    });
                    
                    // Show/hide no results message
                    if (itemsVisible === 0) {
                        noResults.classList.remove('d-none');
                    } else {
                        noResults.classList.add('d-none');
                    }
                });
            });
            
            // Apply button functionality
            const applyButtons = document.querySelectorAll('.btn-apply[data-job]');
            const applyPopup = document.getElementById('applyPopup');
            const closePopup = document.getElementById('closePopup');
            const confirmPopup = document.getElementById('confirmPopup');
            const jobTitlePopup = document.getElementById('job-title-popup');
            
            applyButtons.forEach(button => {
                button.addEventListener('click', function() {
                    const jobTitle = this.getAttribute('data-job');
                    window.location.href = 'hiring.php?job=' + encodeURIComponent(jobTitle);
                });
            });
            
            closePopup.addEventListener('click', function() {
                applyPopup.classList.remove('show');
            });
            
            confirmPopup.addEventListener('click', function() {
                applyPopup.classList.remove('show');
            });
            
            // Back to top button
            const backToTopButton = document.getElementById('backToTop');
            
            window.addEventListener('scroll', function() {
                if (window.pageYOffset > 300) {
                    backToTopButton.classList.add('visible');
                } else {
                    backToTopButton.classList.remove('visible');
                }
            });
            
            backToTopButton.addEventListener('click', function(e) {
                e.preventDefault();
                window.scrollTo({
                    top: 0,
                    behavior: 'smooth'
                });
            });
            
            // Smooth scroll for anchor links
            document.querySelectorAll('a[href^="#"]').forEach(anchor => {
                anchor.addEventListener('click', function (e) {
                    e.preventDefault();
                    
                    const target = document.querySelector(this.getAttribute('href'));
                    if (target) {
                        window.scrollTo({
                            top: target.offsetTop - 100,
                            behavior: 'smooth'
                        });
                    }
                });
            });
        });
    </script>


    
